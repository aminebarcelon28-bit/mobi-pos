#!/usr/bin/env node
/**
 * Dependency inventory + SBOM (repo pass). Dev-only, zero dependencies.
 *
 *   node scripts/gen-sbom.mjs            # writes docs/sbom.json + docs/THIRD_PARTY.md
 *   node scripts/gen-sbom.mjs --check    # fails if a SHIPPED dependency is not
 *                                        # MIT/Apache-2.0/BSD-family, or a licence
 *                                        # is unknown
 *
 * "Shipped" = a `dependencies` entry of the root package (what the bundle may
 * import). Dev tooling is listed separately and never bundled.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const CHECK = process.argv.includes('--check');
const ALLOWED_SET = new Set([
  'MIT',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  '0BSD',
  'BlueOak-1.0.0',
  'CC0-1.0',
  'Unlicense',
  'MIT-0',
  'Python-2.0',
  'WTFPL',
]);
/** Dual licences ("A OR B", "A/B") pass when every alternative is allowed. */
const ALLOWED = (lic) =>
  String(lic)
    .split(/\s+OR\s+|\//i)
    .map((x) => x.trim().replace(/[()]/g, ''))
    .filter(Boolean)
    .every((x) => ALLOWED_SET.has(x));

const rootPkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const lock = JSON.parse(fs.readFileSync(path.join(ROOT, 'package-lock.json'), 'utf8'));
const prod = new Set(Object.keys(rootPkg.dependencies ?? {}));

const licenseOf = (name) => {
  // node_modules is flat here; scoped packages nest one level.
  const p = path.join(ROOT, 'node_modules', name, 'package.json');
  try {
    const pkg = JSON.parse(fs.readFileSync(p, 'utf8'));
    if (typeof pkg.license === 'string') return pkg.license;
    if (pkg.license && typeof pkg.license === 'object' && pkg.license.type) return pkg.license.type;
    if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type).filter(Boolean).join(', ');
    return 'UNKNOWN';
  } catch {
    return 'UNKNOWN';
  }
};

const packages = [];
for (const [key, meta] of Object.entries(lock.packages ?? {})) {
  if (!key.startsWith('node_modules/')) continue;
  const name = key.slice('node_modules/'.length);
  if (!name || name.startsWith('node_modules/')) continue;
  const shipped = prod.has(name) || [...prod].some((d) => name.startsWith(`${d}/`));
  packages.push({
    name,
    version: String(meta.version ?? ''),
    licence: licenseOf(name),
    scope: shipped ? 'runtime' : 'development',
    dev: Boolean(meta.dev),
  });
}
packages.sort((a, b) => (a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name)));

const shipped = packages.filter((p) => p.scope === 'runtime');
const unlicensed = shipped.filter((p) => !ALLOWED(p.licence));
const unknown = shipped.filter((p) => p.licence === 'UNKNOWN');

const sbom = {
  bomFormat: 'SPDX-lite',
  specVersion: '2.3-lite',
  generated: new Date().toISOString(),
  project: { name: rootPkg.name, version: rootPkg.version, licence: 'proprietary' },
  summary: {
    total: packages.length,
    runtime: shipped.length,
    development: packages.length - shipped.length,
    disallowedRuntime: unlicensed.length,
    unknownRuntime: unknown.length,
  },
  packages,
};
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'sbom.json'), JSON.stringify(sbom, null, 2) + '\n');

const rows = shipped
  .map((p) => `| \`${p.name}\` | ${p.version} | ${p.licence} |`)
  .join('\n');
const thirdParty = `# Third-party components (shipped)

Generated by \`npm run sbom\` (\`docs/sbom.json\` is the machine-readable
inventory). Only these packages may be imported by the release bundle; all are
MIT, Apache-2.0 or BSD-family. Development tooling is not listed here and is never
bundled.

| Package | Version | Licence |
|---|---|---|
${rows}

Regenerate after any dependency change: \`npm run sbom\`. The gate
\`npm run gate:licences\` fails if a shipped package is outside the allowlist or
its licence is unknown.
`;
fs.writeFileSync(path.join(ROOT, 'docs', 'THIRD_PARTY.md'), thirdParty);

console.log(
  `[sbom] ${packages.length} packages (${shipped.length} runtime, ${packages.length - shipped.length} dev); ` +
    `runtime outside allowlist: ${unlicensed.length}; unknown: ${unknown.length}`,
);
for (const p of unlicensed) console.log(`  DISALLOWED ${p.name}@${p.version} :: ${p.licence}`);
for (const p of unknown) console.log(`  UNKNOWN   ${p.name}@${p.version}`);

if (CHECK && unlicensed.length > 0) process.exit(1);
process.exit(0);
